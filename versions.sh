#!/bin/bash

BOOKWORM_BASE_VERSION='1.22.1-9+deb12u10'
BOOKWORM_HOTFIX_VERSION='1.22.1-9+deb12u10.1~hp1'
BOOKWORM_DEBIAN_POINT_VERSION='1.22.1-9+deb12u10.1'
BOOKWORM_DEBIAN_NEXT_VERSION='1.22.1-9+deb12u11'
BOOKWORM_ORIG_FILE='nginx_1.22.1.orig.tar.gz'
BOOKWORM_ORIG_SHA256='9ebb333a9e82b952acd3e2b4aeb1d4ff6406f72491bab6cd9fe69f0dea737f31'
BOOKWORM_DEBIAN_FILE='nginx_1.22.1-9+deb12u10.debian.tar.xz'
BOOKWORM_DEBIAN_SHA256='a5a60f970ef19c926da4f71a0398d00f3fccf4f35169f0994c7d6573d148d63f'

TRIXIE_BASE_VERSION='1.26.3-3+deb13u10'
TRIXIE_HOTFIX_VERSION='1.26.3-3+deb13u10.1~hp1'
TRIXIE_DEBIAN_POINT_VERSION='1.26.3-3+deb13u10.1'
TRIXIE_DEBIAN_NEXT_VERSION='1.26.3-3+deb13u11'
TRIXIE_ORIG_FILE='nginx_1.26.3.orig.tar.gz'
TRIXIE_ORIG_SHA256='69ee2b237744036e61d24b836668aad3040dda461fe6f570f1787eab570c75aa'
TRIXIE_DEBIAN_FILE='nginx_1.26.3-3+deb13u10.debian.tar.xz'
TRIXIE_DEBIAN_SHA256='22b58b7a5261cd427022544814d502935aba9d84bf2ca4e03d9f7a17e678c388'

nginx_release_vars() {
    case "$1" in
        12)
            RELEASE_CODENAME=bookworm
            BASE_VERSION=$BOOKWORM_BASE_VERSION
            HOTFIX_VERSION=$BOOKWORM_HOTFIX_VERSION
            DEBIAN_POINT_VERSION=$BOOKWORM_DEBIAN_POINT_VERSION
            DEBIAN_NEXT_VERSION=$BOOKWORM_DEBIAN_NEXT_VERSION
            ORIG_FILE=$BOOKWORM_ORIG_FILE
            ORIG_SHA256=$BOOKWORM_ORIG_SHA256
            DEBIAN_FILE=$BOOKWORM_DEBIAN_FILE
            DEBIAN_SHA256=$BOOKWORM_DEBIAN_SHA256
            ;;
        13)
            RELEASE_CODENAME=trixie
            BASE_VERSION=$TRIXIE_BASE_VERSION
            HOTFIX_VERSION=$TRIXIE_HOTFIX_VERSION
            DEBIAN_POINT_VERSION=$TRIXIE_DEBIAN_POINT_VERSION
            DEBIAN_NEXT_VERSION=$TRIXIE_DEBIAN_NEXT_VERSION
            ORIG_FILE=$TRIXIE_ORIG_FILE
            ORIG_SHA256=$TRIXIE_ORIG_SHA256
            DEBIAN_FILE=$TRIXIE_DEBIAN_FILE
            DEBIAN_SHA256=$TRIXIE_DEBIAN_SHA256
            ;;
        *)
            echo "unsupported Debian release: $1" >&2
            return 1
            ;;
    esac
}
